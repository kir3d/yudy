"""Create the bundled CoinGecko market-chart fallback for official xStocks."""

from __future__ import annotations

import json
import sys
import urllib.parse
import urllib.request
from datetime import datetime, timezone
from pathlib import Path


ROOT = Path(__file__).parents[1]
sys.path.insert(0, str(ROOT / "src"))

from xstocks_catalog import CATALOG  # noqa: E402


BASE_URL = "https://api.coingecko.com/api/v3"
query = urllib.parse.urlencode({
    "vs_currency": "usd",
    "category": "xstocks-ecosystem",
    "order": "market_cap_desc",
    "per_page": 250,
    "page": 1,
    "sparkline": "true",
    "price_change_percentage": "24h,7d",
})
request = urllib.request.Request(f"{BASE_URL}/coins/markets?{query}", headers={
    "Accept": "application/json",
    "User-Agent": "YUDY/0.1 (+https://yudyai.xyz)",
})
with urllib.request.urlopen(request, timeout=60) as response:
    payload = json.load(response)

symbols = {str(item["symbol"]).casefold() for item in CATALOG["nodes"]}
fields = (
    "id", "symbol", "current_price", "market_cap", "total_volume", "high_24h",
    "low_24h", "price_change_percentage_24h_in_currency",
    "price_change_percentage_7d_in_currency", "ath", "sparkline_in_7d",
)
markets = {
    str(item["symbol"]).casefold(): {key: item.get(key) for key in fields}
    for item in payload
    if str(item.get("symbol") or "").casefold() in symbols
}
target = ROOT / "src" / "coingecko_snapshot.py"
snapshot = {
    "source": f"{BASE_URL}/coins/markets",
    "captured_at": datetime.now(timezone.utc).isoformat(),
    "markets": markets,
}
target.write_text(
    "# Generated by scripts/snapshot_coingecko.py\nSNAPSHOT = " + repr(snapshot) + "\n",
    encoding="utf-8",
)
print(f"wrote {len(markets)} CoinGecko xStocks to {target}")
