"""Generate a deterministic D1 seed migration from the existing demo manifests."""

from __future__ import annotations

import hashlib
import json
import uuid
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "worker-backend" / "migrations" / "0002_seed.sql"
STAMP = "2026-10-06T00:00:00+00:00"
NAMESPACE = uuid.UUID("bf16f7ee-9c2d-4a19-86ca-56b45f3a0135")


def load(relative: str) -> dict[str, Any]:
    return json.loads((ROOT / relative).read_text(encoding="utf-8"))


def uid(kind: str, value: str) -> str:
    return str(uuid.uuid5(NAMESPACE, f"{kind}:{value}"))


def sql(value: Any) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "1" if value else "0"
    if isinstance(value, (int, float)):
        return repr(value)
    return "'" + str(value).replace("'", "''") + "'"


def insert(table: str, columns: list[str], values: list[Any]) -> str:
    return (
        f"INSERT INTO {table} ({', '.join(columns)}) VALUES "
        f"({', '.join(sql(value) for value in values)});"
    )


def main() -> None:
    taxonomy = load("backend/taxonomy/manifest.json")
    risk = load("backend/risk/manifest.json")
    learn = load("backend/learn/manifest.json")
    legal = load("backend/legal/manifest.json")
    market = load("backend/market/manifest.json")

    lines = [
        "-- Generated by scripts/generate_seed.py. Do not edit by hand.",
        "PRAGMA foreign_keys = ON;",
        "",
    ]

    for item in taxonomy["goals"]:
        lines.append(
            insert(
                "goals",
                ["id", "code", "title", "active"],
                [uid("goal", item["code"]), item["code"], item["title"], True],
            )
        )
    for item in taxonomy["interests"]:
        lines.append(
            insert(
                "interests",
                ["id", "code", "title", "kind", "active"],
                [uid("interest", item["code"]), item["code"], item["title"], item["kind"], True],
            )
        )
    for item in taxonomy["regions"]:
        lines.append(
            insert(
                "regions",
                ["id", "code", "title", "active"],
                [uid("region", item["code"]), item["code"], item["title"], True],
            )
        )

    lines.append("")
    for item in legal["documents"]:
        content = (ROOT / "backend" / "legal" / item["content_file"]).read_text(encoding="utf-8")
        lines.append(
            insert(
                "legal_documents",
                ["id", "type", "version", "title", "content", "is_mandatory", "active", "created_at"],
                [
                    uid("legal", f"{item['type']}:{item['version']}"),
                    item["type"],
                    item["version"],
                    item["title"],
                    content,
                    item["is_mandatory"],
                    True,
                    STAMP,
                ],
            )
        )

    lines.append("")
    questionnaire_json = json.dumps(risk, sort_keys=True, separators=(",", ":"))
    questionnaire_id = uid("risk-questionnaire", risk["version"])
    lines.append(
        insert(
            "risk_questionnaires",
            ["id", "version", "content_hash", "conservative_max", "balanced_max", "active"],
            [
                questionnaire_id,
                risk["version"],
                hashlib.sha256(questionnaire_json.encode()).hexdigest(),
                risk["conservative_max"],
                risk["balanced_max"],
                True,
            ],
        )
    )
    for question_order, question in enumerate(risk["questions"]):
        question_id = uid("risk-question", f"{risk['version']}:{question['code']}")
        lines.append(
            insert(
                "risk_questions",
                ["id", "questionnaire_id", "code", "text", "sort_order", "active"],
                [question_id, questionnaire_id, question["code"], question["text"], question_order, True],
            )
        )
        for option_order, option in enumerate(question["options"]):
            lines.append(
                insert(
                    "risk_answer_options",
                    ["id", "question_id", "code", "text", "score", "sort_order"],
                    [
                        uid("risk-option", f"{risk['version']}:{question['code']}:{option['code']}"),
                        question_id,
                        option["code"],
                        option["text"],
                        option["score"],
                        option_order,
                    ],
                )
            )

    lines.append("")
    for article in learn["articles"]:
        lines.append(
            insert(
                "learn_articles",
                ["id", "slug", "title", "summary", "content", "sort_order", "active", "created_at", "updated_at"],
                [
                    uid("article", article["slug"]),
                    article["slug"],
                    article["title"],
                    article["summary"],
                    article["content"],
                    article["sort_order"],
                    article.get("active", True),
                    STAMP,
                    STAMP,
                ],
            )
        )

    lines.append("")
    for asset in market["assets"]:
        asset_id = uid("asset", asset["symbol"])
        lines.append(
            insert(
                "assets",
                [
                    "id", "symbol", "name", "asset_type", "description", "sector", "industry",
                    "country", "region", "market", "logo_url", "currency", "active", "created_at", "updated_at",
                ],
                [
                    asset_id,
                    asset["symbol"],
                    asset["name"],
                    asset["asset_type"],
                    asset["description"],
                    asset.get("sector"),
                    asset.get("industry"),
                    asset.get("country"),
                    asset.get("region"),
                    asset.get("market"),
                    asset.get("logo_url"),
                    asset["currency"],
                    asset.get("active", True),
                    STAMP,
                    STAMP,
                ],
            )
        )
        for theme_code in asset.get("theme_codes", []):
            lines.append(
                insert(
                    "asset_themes",
                    ["asset_id", "interest_id"],
                    [asset_id, uid("interest", theme_code)],
                )
            )
        fundamentals = asset.get("fundamentals")
        if fundamentals:
            fields = [
                "price", "market_cap", "pe", "eps", "revenue", "revenue_growth",
                "net_income", "debt", "cash_flow", "dividend", "dividend_yield",
            ]
            lines.append(
                insert(
                    "asset_fundamentals",
                    ["asset_id", *fields, "updated_at"],
                    [asset_id, *(fundamentals.get(field) for field in fields), STAMP],
                )
            )
        for point in asset.get("prices", []):
            lines.append(
                insert(
                    "asset_prices",
                    ["asset_id", "timestamp", "open", "high", "low", "close", "volume"],
                    [
                        asset_id,
                        point["timestamp"],
                        point["open"],
                        point["high"],
                        point["low"],
                        point["close"],
                        point.get("volume"),
                    ],
                )
            )
        for token in asset.get("tokens", []):
            token_id = uid("token", f"{asset['symbol']}:{token['symbol']}")
            fields = [
                "symbol", "token_name", "issuer", "tokenization_provider", "backing",
                "proof_of_reserves_url", "oracle_provider", "oracle_reference",
                "corporate_actions_info", "availability", "external_provider_id", "external_buy_url",
            ]
            lines.append(
                insert(
                    "tokenized_assets",
                    ["id", "asset_id", *fields, "active", "created_at", "updated_at"],
                    [
                        token_id,
                        asset_id,
                        *(token.get(field) for field in fields),
                        token.get("active", True),
                        STAMP,
                        STAMP,
                    ],
                )
            )
        for risk_item in asset.get("risks", []):
            lines.append(
                insert(
                    "asset_risks",
                    ["id", "asset_id", "title", "description", "sort_order", "active"],
                    [
                        uid("asset-risk", f"{asset['symbol']}:{risk_item['sort_order']}:{risk_item['title']}"),
                        asset_id,
                        risk_item["title"],
                        risk_item["description"],
                        risk_item["sort_order"],
                        True,
                    ],
                )
            )

    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)} with {len(lines)} statements/lines")


if __name__ == "__main__":
    main()
