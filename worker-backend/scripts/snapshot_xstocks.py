"""Create the bundled fallback from the official public xStocks catalog."""

from __future__ import annotations

import json
import urllib.error
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime, timezone
from pathlib import Path


BASE_URL = "https://api.xstocks.fi/api/v2/public/assets"
SYMBOLS = (
    "AAPLx", "ABBVx", "ABTx", "ACNx", "ADBx", "AMDx", "AMZNx", "AVGOx",
    "BACx", "BRK.Bx", "COINx", "CRCLx", "CSCOx", "CVXx", "DISx", "GLDx",
    "GOOGLx", "GMEx", "HOODx", "IBITx", "INTCx", "IWMx", "JNJx", "JPMx",
    "KOx", "LLYx", "MAx", "MCDx", "METAx", "MRKx", "MSFTx", "MSTRx",
    "NFLXx", "NVDAx", "ORCLx", "PEPx", "PFEx", "PLTRx", "PYPLx", "QQQx",
    "SPCXx", "SPYx", "STRCx", "TLTx", "TSLAx", "UNHx", "VTIx", "Vx",
    "WMTx", "XOMx",
)


def fetch_symbol(symbol: str):
    url = f"{BASE_URL}/{symbol}"
    request = urllib.request.Request(url, headers={
        "Accept": "application/json",
        "User-Agent": "YUDY/0.1 (+https://yudyai.xyz)",
    })
    try:
        with urllib.request.urlopen(request, timeout=60) as response:
            return json.load(response)
    except urllib.error.HTTPError as error:
        if error.code == 404:
            return None
        raise


with ThreadPoolExecutor(max_workers=8) as pool:
    source_nodes = [item for item in pool.map(fetch_symbol, SYMBOLS) if item]

nodes = []
for item in source_nodes:
    nodes.append({
        key: item.get(key)
        for key in (
            "id", "name", "symbol", "underlyingSymbol", "description", "logo",
            "isTradingHalted", "underlying", "deployments",
        )
    })

target = Path(__file__).parents[1] / "src" / "xstocks_catalog.py"
catalog = {
    "source": BASE_URL,
    "captured_at": datetime.now(timezone.utc).isoformat(),
    "nodes": nodes,
}
target.write_text("# Generated by scripts/snapshot_xstocks.py\nCATALOG = " + repr(catalog) + "\n",
    encoding="utf-8")
print(f"wrote {len(nodes)} official xStocks to {target}")
